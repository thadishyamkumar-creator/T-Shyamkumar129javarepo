class Switchcase{

      public static void main(String[] args ){
	  
	  final byte i=3;
	  
	   switch(i){
		   case 5:
			System.out.println("five");
			break;
		   case 0:
			System.out.println("ten");
			break;
		   case 3:
			System.out.println("fifteen");
			break;
		   default:
			System.out.println("default case");
			break;
		}
	}
}